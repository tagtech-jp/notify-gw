-- モデル deprecation 監視の土台。
--
-- 2026-05-15 から4ヶ月、CI の CLOUDFLARE_API_TOKEN が失効していたのに誰も気づかなかった。
-- 同じ構造が LLM のフォールバック階層にもある。4層のうち1層が「そのモデルはもう無い」と
-- 言い出しても上位層が拾えば動いてしまい、黙って劣化する。
--
-- 監視対象は「設定に外部化されているモデル名すべて」。プロバイダ単位で固定すると、
-- 設定を変えたときに監視が追随しない。そこで各 Worker が自分の vars にあるモデル名を
-- バインディング申告と同じ経路で自己申告し、cto-tech-monitor がそれを集めて
-- 各提供元の一覧 API と照合する。
--
-- 【非破壊であることの根拠】
--   * ALTER TABLE ... ADD COLUMN のみ。既存の列・行・インデックスに触れない
--   * NOT NULL 制約を付けず、既定値も置かないので既存行は models = NULL のまま残る
--   * 読み出し側は NULL を「モデル未申告」として扱う(0009 適用前の申告と区別できる)
--   * INSERT 文は列名を明示しているため、この列が増えても既存の書き込みは壊れない
--   * SQLite の ADD COLUMN は表の書き換えを伴わないため、既存データの再構築が起きない

ALTER TABLE binding_reports ADD COLUMN models TEXT;

-- models の形: JSON 配列。どの変数に何が設定されているかを保つ。
--   [{"var":"ANTHROPIC_MODEL","model":"claude-haiku-4-5-20251001"}, ...]
-- 値だけの配列にしないのは、CRITICAL が出たときに
-- 「どの Worker のどの変数を直せばよいか」が分からなくなるため。
